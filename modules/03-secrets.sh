#!/bin/bash

# ==============================================================================
# 03-secrets.sh
#
# Управляет паролями БД и администратора.
#
# Блоки:
# 01. Создание каталога секретов.
# 02. Миграция старых секретов из прежней структуры.
# 03. Пароль базы данных.
# 04. Пароль администратора.
# 05. Вывод путей к файлам паролей.
# ==============================================================================

# ------------------------------------------------------------------------------
# 01. Создание каталога секретов.
# ------------------------------------------------------------------------------
mkdir -p "$SECRET_DIR"

# ------------------------------------------------------------------------------
# 02. Миграция старых секретов.
#
# Раньше секреты могли лежать в /mikrobill-data/data/secrets.
# Сейчас каноническое место: /mikrobill-data/secrets.
# ------------------------------------------------------------------------------
for f in db_password admin_password; do
    if [ ! -s "$SECRET_DIR/$f" ] && [ -f "${DATA_DIR}/secrets/$f" ]; then
        cp "${DATA_DIR}/secrets/$f" "$SECRET_DIR/$f"
    fi
done

# ------------------------------------------------------------------------------
# 03. Пароль базы данных.
#
# Если задан DB_PASSWORD — используем его.
# Если нет — генерируем один раз и сохраняем.
# ------------------------------------------------------------------------------
if [ -n "${DB_PASSWORD:-}" ]; then
    printf '%s' "$DB_PASSWORD" > "$SECRET_DIR/db_password"
fi

if [ ! -s "$SECRET_DIR/db_password" ]; then
    openssl rand -hex 16 > "$SECRET_DIR/db_password"
fi

DB_PASSWORD=$(cat "$SECRET_DIR/db_password")
chmod 600 "$SECRET_DIR/db_password"

# ------------------------------------------------------------------------------
# 04. Пароль администратора.
#
# Если задан ADMIN_PASSWORD — используем его.
# Если нет — генерируем один раз и сохраняем.
# ------------------------------------------------------------------------------
if [ -n "${ADMIN_PASSWORD:-}" ]; then
    printf '%s' "$ADMIN_PASSWORD" > "$SECRET_DIR/admin_password"
fi

if [ ! -s "$SECRET_DIR/admin_password" ]; then
    openssl rand -hex 12 > "$SECRET_DIR/admin_password"
fi

ADMIN_PASSWORD=$(cat "$SECRET_DIR/admin_password")
chmod 600 "$SECRET_DIR/admin_password"

# ------------------------------------------------------------------------------
# 05. Вывод путей.
# ------------------------------------------------------------------------------
echo "DB password file: $SECRET_DIR/db_password"
echo "Admin password file: $SECRET_DIR/admin_password"
